# Smart-UV + AO bake and procedural detail textures for the main DataCool asset groups.
#
# Per asset group (rack / exchanger / district / loops) the meshes are joined into
# '<group>__baked', smart-unwrapped (UV0) and AO-baked. Every material is then rebuilt as a
# glTF-friendly PBR material:
#   * base colour  = base colour * AO baked into UV0 (JPEG)      [or a procedural facade]
#   * detail maps on a second, world-space box-projected UV map ('UVDetail' -> TEXCOORD_1):
#       metallic-roughness (brushed metal / grain), normal (brushed, grain, plate chevron),
#       emissive (lit windows) - generated by procedural_textures.py, configured by the
#       'detail' block of scene_layout.json
#   * constant emission (LEDs, warm cold plates) from the material's 'emissive' entry
# then written to pipeline/textures, scene_baked.blend and a plain-glTF GLB (no Draco).
#
#   blender.exe -b --factory-startup -P pipeline/bake.py -- --quick
#   blender.exe -b --factory-startup -P pipeline/bake.py

