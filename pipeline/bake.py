import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import procedural_textures as pt  # noqa: E402

# The glTF exporter writes textures through tempfile.TemporaryDirectory(). Python 3.13
# creates those directories owner-only, which a confined (sandboxed) token cannot
# write to. Plain makedirs() directories inherit the workspace ACL instead.
class _OpenTemporaryDirectory:
    def __init__(self, *args, **kwargs):
        base = os.environ.get("TEMP") or tempfile.gettempdir()
        self.name = os.path.join(base, "dc_" + uuid.uuid4().hex[:10])
        os.makedirs(self.name, exist_ok=True)
    def __enter__(self):
        return self.name
    def __exit__(self, *exc):
        self.cleanup()
    def cleanup(self):
        shutil.rmtree(self.name, ignore_errors=True)

tempfile.TemporaryDirectory = _OpenTemporaryDirectory

with open(os.path.join(HERE, "scene_layout.json"), "r", encoding="utf-8") as fh:
    LAYOUT = json.load(fh)
DETAIL = LAYOUT.get("detail", {})
MATSPEC = LAYOUT["materials"]

def abs_path(rel):
    return os.path.normpath(os.path.join(ROOT, rel))

# DATACOOL_OUT=<dir> re-roots products (blends, textures, glb) under <ROOT>/<dir>/.
OUT_ROOT = os.environ.get("DATACOOL_OUT")

def out_path(rel):
    if os.path.isabs(rel):
        return rel
    base = os.path.join(ROOT, OUT_ROOT) if OUT_ROOT and not os.path.isabs(OUT_ROOT) else (OUT_ROOT or ROOT)
    return os.path.normpath(os.path.join(base, rel))

def log(*args):
    print("[bake]", *args, flush=True)

def parse_args():
    argv = sys.argv
    argv = argv[argv.index("--") + 1:] if "--" in argv else []
    opts = {"quick": False, "groups": None, "blend": None}
    i = 0
    while i < len(argv):
        if argv[i] == "--quick":
            opts["quick"] = True; i += 1
        elif argv[i] == "--groups" and i + 1 < len(argv):
            opts["groups"] = [g.strip() for g in argv[i + 1].split(",") if g.strip()]; i += 2
        elif argv[i] == "--blend" and i + 1 < len(argv):
            opts["blend"] = abs_path(argv[i + 1]); i += 2
        else:
            i += 1
    return opts

def linear_to_srgb(a):
    return np.where(a <= 0.0031308, a * 12.92, 1.055 * np.power(np.clip(a, 0, None), 1 / 2.4) - 0.055)

def srgb_to_linear_hex(value):
    value = value.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(value[i:i + 2], 16) / 255.0
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return tuple(out) + (1.0,)

def select_only(obj):
    bpy.ops.object.select_all(action='DESELECT')
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj

def principled(mat):
    if not mat.use_nodes:
        return None
    for node in mat.node_tree.nodes:
        if node.type == 'BSDF_PRINCIPLED':
            return node
    return None

def base_name(mat):
    """'rack__stainless' -> 'stainless'."""
    n = mat.name.split("__", 1)[-1]
    return n.split(".")[0]

# ------------------------------------------------------------------ image helpers

IMAGE_CACHE = {}
TEXTURE_LOG = {}

def write_image(arr, name, texture_dir, fmt, colorspace):
    """arr: (h, w, 3) float32, row 0 = bottom. Saved to disk, then re-loaded as a
    file-backed image so the glTF exporter embeds the bytes untouched."""
    key = (name, fmt, colorspace)
    if key in IMAGE_CACHE:
        return IMAGE_CACHE[key]
    h, w = arr.shape[:2]
    rgba = np.ones((h, w, 4), np.float32)
    rgba[..., :3] = np.clip(arr, 0.0, 1.0)
    tmp = bpy.data.images.new(name + "_gen", width=w, height=h, alpha=False)
    tmp.colorspace_settings.name = 'sRGB' if colorspace == 'sRGB' else 'Non-Color'
    tmp.pixels.foreach_set(rgba.ravel())
    ext = ".jpg" if fmt == 'JPEG' else ".png"
    safe = "".join(c if c.isalnum() or c in "-_." else "_" for c in name)
    path = os.path.join(texture_dir, safe + ext)
    tmp.filepath_raw = path
    tmp.file_format = fmt
    tmp.save()
    bpy.data.images.remove(tmp)
    img = bpy.data.images.load(path)
    img.name = safe
    img.colorspace_settings.name = 'sRGB' if colorspace == 'sRGB' else 'Non-Color'
    IMAGE_CACHE[key] = img
    TEXTURE_LOG.setdefault("files", []).append(os.path.basename(path))
    return img

def mr_image(cfg, texture_dir):
    s = cfg.get("size", 512)
    name = "mr_%s_m%.2f_r%.2f_v%.2f" % (cfg["kind"], cfg["metal"], cfg["rough"], cfg["var"])
    key = (name, 'JPEG', 'Non-Color')
    if key in IMAGE_CACHE:
        return IMAGE_CACHE[key]
    arr = pt.mr_texture(s, cfg["kind"], cfg["metal"], cfg["rough"], cfg["var"])
    return write_image(arr, name, texture_dir, 'JPEG', 'Non-Color')

def normal_image(cfg, texture_dir):
    s = cfg.get("size", 512)
    name = "n_%s_s%.2f" % (cfg["kind"], cfg["strength"])
    key = (name, 'PNG', 'Non-Color')
    if key in IMAGE_CACHE:
        return IMAGE_CACHE[key]
    arr = pt.normal_texture(s, cfg["kind"], cfg["strength"])
    return write_image(arr, name, texture_dir, 'PNG', 'Non-Color')

# ------------------------------------------------------------------ detail UV map

def add_detail_uv(obj, tiles):
    """World-space box projection into a second UV layer 'UVDetail'.
    tiles: material slot index -> dict(tile_m=[tu, tv], roof_fixed=bool)."""
    me = obj.data
    nl, npoly = len(me.loops), len(me.polygons)
    lv = np.empty(nl, np.int32)
    me.loops.foreach_get("vertex_index", lv)
    co = np.empty(len(me.vertices) * 3, np.float32)
    me.vertices.foreach_get("co", co)
    co = co.reshape(-1, 3)
    pn = np.empty(npoly * 3, np.float32)
    me.polygons.foreach_get("normal", pn)
    pn = pn.reshape(-1, 3)
    lt = np.empty(npoly, np.int32)
    me.polygons.foreach_get("loop_total", lt)
    mi = np.empty(npoly, np.int32)
    me.polygons.foreach_get("material_index", mi)

    loop_poly = np.repeat(np.arange(npoly), lt)
    P = co[lv]
    ax = np.argmax(np.abs(pn[loop_poly]), axis=1)
    u = np.where(ax == 0, P[:, 1], P[:, 0])
    v = np.where(ax == 2, P[:, 1], P[:, 2])

    nslots = max(tiles.keys()) + 1 if tiles else 1
    tu = np.ones(nslots, np.float32)
    tv = np.ones(nslots, np.float32)
    roof = np.zeros(nslots, bool)
    for slot, t in tiles.items():
        tu[slot], tv[slot] = t["tile_m"]
        roof[slot] = t.get("roof_fixed", False)
    lm = mi[loop_poly]
    uvs = np.stack([u / tu[lm], v / tv[lm]], axis=1)
    fixed = roof[lm] & (ax == 2)
    uvs[fixed] = 0.004
    layer = me.uv_layers.new(name="UVDetail")
    layer.data.foreach_set("uv", uvs.astype(np.float32).ravel())
    return "UVDetail"

# ------------------------------------------------------------------ material rebuild

def rebuild_material(mat, albedo_img, uv0, uvd, cfg, spec, texture_dir):
    """Rewrite mat as UV0 albedo (+ UVDetail mr / normal / emissive) Principled PBR."""
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    old = principled(mat)
    metallic = float(old.inputs["Metallic"].default_value) if old else 0.0
    roughness = float(old.inputs["Roughness"].default_value) if old else 0.5
    nodes.clear()
    out = nodes.new("ShaderNodeOutputMaterial")
    bsdf = nodes.new("ShaderNodeBsdfPrincipled")
    links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    used = []

    def tex_node(image, uvname, colorspace):
        t = nodes.new("ShaderNodeTexImage")
        t.image = image
        t.extension = 'REPEAT'
        t.interpolation = 'Linear'
        uvn = nodes.new("ShaderNodeUVMap")
        uvn.uv_map = uvname
        links.new(uvn.outputs["UV"], t.inputs["Vector"])
        return t

    if albedo_img is not None:
        t = tex_node(albedo_img, uv0, 'sRGB')
        links.new(t.outputs["Color"], bsdf.inputs["Base Color"])
        used.append("baseColor")

    if "mr" in cfg:
        img = mr_image(cfg["mr"], texture_dir)
        t = tex_node(img, uvd, 'Non-Color')
        sep = nodes.new("ShaderNodeSeparateColor")
        links.new(t.outputs["Color"], sep.inputs["Color"])
        links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
        links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
        used.append("metallicRoughness")
    if "mr_image" in cfg:       # facade: pre-built image
        t = tex_node(cfg["mr_image"], uvd, 'Non-Color')
        sep = nodes.new("ShaderNodeSeparateColor")
        links.new(t.outputs["Color"], sep.inputs["Color"])
        links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
        links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
        used.append("metallicRoughness")
    if "normal" in cfg:
        img = normal_image(cfg["normal"], texture_dir)
        t = tex_node(img, uvd, 'Non-Color')
        nm = nodes.new("ShaderNodeNormalMap")
        nm.uv_map = uvd
        nm.inputs["Strength"].default_value = 1.0
        links.new(t.outputs["Color"], nm.inputs["Color"])
        links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
        used.append("normal")
    if "emissive_image" in cfg:
        t = tex_node(cfg["emissive_image"], uvd, 'sRGB')
        links.new(t.outputs["Color"], bsdf.inputs["Emission Color"])
        bsdf.inputs["Emission Strength"].default_value = 1.0
        used.append("emissive(map)")
    elif spec.get("emissive"):
        em = spec["emissive"]
        bsdf.inputs["Emission Color"].default_value = srgb_to_linear_hex(em["hex"])
        bsdf.inputs["Emission Strength"].default_value = float(em.get("strength", 1.0))
        used.append("emissive(const)")
    TEXTURE_LOG.setdefault("materials", {})[mat.name] = used

def bake_group(name, resolution, samples, texture_dir):
    col = bpy.data.collections.get(name)
    if col is None:
        log("SKIP group (no collection):", name)
        return None
    meshes = [o for o in col.all_objects if o.type == 'MESH']
    if not meshes:
        log("SKIP group (no meshes):", name)
        return None

    # Big flat objects (the 240 m district slab) get a useless, streaky smart-UV AO
    # texture; keep them out of the join/bake and give them an independent flat material.
    tokens = [t.lower() for t in LAYOUT["bake"].get("exclude", {}).get(name, [])]
    excluded = [o for o in meshes if any(t in o.name.lower() for t in tokens)]
    for o in excluded:
        for i, m in enumerate(o.data.materials):
            if m is not None:
                flat = m.copy()
                flat.name = m.name + "_flat"
                o.data.materials[i] = flat
        log("excluded from bake (flat material):", o.name)
    meshes = [o for o in meshes if o not in excluded]
    if not meshes:
        return None

    started = time.time()
    log("group", name, "objects", len(meshes), "res", resolution, "samples", samples)

    # ---- join within this asset only, bake to world space
    select_only(meshes[0])
    for obj in meshes[1:]:
        obj.select_set(True)
    if len(meshes) > 1:
        bpy.ops.object.join()
    obj = bpy.context.view_layer.objects.active
    obj.name = name + "__baked"
    bpy.ops.object.parent_clear(type='CLEAR_KEEP_TRANSFORM')
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)

    # ---- smart UV unwrap (UV0, used for the AO-baked albedo)
    select_only(obj)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=math.radians(66.0), island_margin=0.02)
    bpy.ops.object.mode_set(mode='OBJECT')

    me = obj.data
    if not me.uv_layers:
        log("ERROR no UV layer on", name)
        return None
    uv_name = me.uv_layers[0].name

    # ---- AO image shared by every material in the group
    ao_img = bpy.data.images.new("AO_" + name, width=resolution, height=resolution,
                                 alpha=False)
    ao_img.colorspace_settings.name = 'Non-Color'

    for slot in obj.material_slots:
        mat = slot.material
        if mat is None:
            continue
        mat.use_nodes = True
        nodes, links = mat.node_tree.nodes, mat.node_tree.links
        tex = nodes.new("ShaderNodeTexImage")
        tex.name = "DataCool AO Target"
        tex.image = ao_img
        tex.select = True
        nodes.active = tex
        # bake requires the image node to be part of the active material tree
        if not any(n.type == 'BSDF_PRINCIPLED' for n in nodes):
            bsdf = nodes.new("ShaderNodeBsdfPrincipled")
            out = nodes.get("Material Output") or nodes.new("ShaderNodeOutputMaterial")
            links.new(bsdf.outputs["BSDF"], out.inputs["Surface"])

    scene = bpy.context.scene
    scene.render.engine = 'CYCLES'
    scene.cycles.device = 'CPU'
    scene.cycles.samples = samples
    scene.render.bake.margin = LAYOUT["bake"]["margin"]
    scene.render.bake.use_clear = True

    select_only(obj)
    bpy.ops.object.bake(type='AO', use_clear=True)
    log("baked AO", name, "%.1fs" % (time.time() - started))

    ao_path = os.path.join(texture_dir, "ao_%s.png" % name)
    ao_img.filepath_raw = ao_path
    ao_img.file_format = 'PNG'
    ao_img.save()
    log("WROTE", ao_path)

    # ---- second UV layer: world-space box projection for the detail maps
    tiles = {}
    for i, slot in enumerate(obj.material_slots):
        if slot.material is None:
            continue
        cfg = DETAIL.get(base_name(slot.material), {})
        tiles[i] = {"tile_m": cfg.get("tile_m", [1.0, 1.0]),
                    "roof_fixed": "facade" in cfg}
    uvd = add_detail_uv(obj, tiles)

    # ---- build linear AO array once
    w, h = ao_img.size
    raw = np.empty(w * h * 4, dtype=np.float32)
    ao_img.pixels.foreach_get(raw)
    ao = np.clip(raw.reshape(h, w, 4)[:, :, :3], 0.0, 1.0)

    # ---- rebuild every material
    for slot in obj.material_slots:
        mat = slot.material
        if mat is None:
            continue
        bsdf = principled(mat)
        if bsdf is None:
            continue
        bname = base_name(mat)
        cfg = dict(DETAIL.get(bname, {}))
        spec = MATSPEC.get(bname, {})
        albedo_img = None
        if "facade" in cfg:
            fc = cfg["facade"]
            tag = "facade_%dx%d" % (fc["cols"], fc["rows"])
            alb, emi, mrf = pt.facade_textures(fc.get("size", 1024), fc["cols"], fc["rows"],
                                               fc["lit_prob"], fc["wall_hex"], fc["glass_hex"])
            albedo_img = write_image(alb, tag + "_albedo", texture_dir, 'JPEG', 'sRGB')
            cfg["emissive_image"] = write_image(emi, tag + "_emissive", texture_dir, 'JPEG', 'sRGB')
            cfg["mr_image"] = write_image(mrf, tag + "_mr", texture_dir, 'JPEG', 'Non-Color')
            # facade albedo lives on the detail UV map
            rebuild_material(mat, None, uv_name, uvd, cfg, spec, texture_dir)
            # attach the albedo on UVDetail
            nodes, links = mat.node_tree.nodes, mat.node_tree.links
            bs = principled(mat)
            t = nodes.new("ShaderNodeTexImage")
            t.image = albedo_img
            t.extension = 'REPEAT'
            uvn = nodes.new("ShaderNodeUVMap")
            uvn.uv_map = uvd
            links.new(uvn.outputs["UV"], t.inputs["Vector"])
            links.new(t.outputs["Color"], bs.inputs["Base Color"])
            TEXTURE_LOG["materials"][mat.name].insert(0, "baseColor(facade)")
            continue

        base = np.array(bsdf.inputs["Base Color"].default_value[:3], dtype=np.float32)
        albedo = linear_to_srgb(np.clip(ao * base[None, None, :], 0.0, 1.0))
        albedo_img = write_image(albedo, "%s_ao" % mat.name, texture_dir, 'JPEG', 'sRGB')
        rebuild_material(mat, albedo_img, uv_name, uvd, cfg, spec, texture_dir)

    obj.data.calc_loop_triangles()
    info = {
        "group": name,
        "objects_joined": len(meshes),
        "triangles": len(obj.data.loop_triangles),
        "resolution": resolution,
        "uv_layers": [l.name for l in obj.data.uv_layers],
        "materials": [s.material.name for s in obj.material_slots if s.material],
        "seconds": round(time.time() - started, 2),
    }
    log("group done", json.dumps(info))
    return info

def main():
    opts = parse_args()
    blend = opts["blend"] or out_path(LAYOUT["outputs"]["blend"])
    if not os.path.isfile(blend):
        log("ERROR missing blend:", blend)
        sys.exit(2)
    bpy.ops.wm.open_mainfile(filepath=blend)
    texture_dir = out_path(LAYOUT["bake"]["texture_dir"])
    os.makedirs(texture_dir, exist_ok=True)

    groups = opts["groups"] or list(LAYOUT["bake"]["groups"].keys())
    report = {"quick": opts["quick"], "groups": []}
    for name in groups:
        res = LAYOUT["bake"]["groups"].get(name, 1024)
        if opts["quick"]:
            res = min(res, LAYOUT["bake"]["quick_resolution"])
            samples = LAYOUT["bake"]["quick_samples"]
        else:
            samples = LAYOUT["bake"]["full_samples"]
        info = bake_group(name, res, samples, texture_dir)
        if info:
            report["groups"].append(info)

    baked_blend = out_path(LAYOUT["outputs"]["baked_blend"])
    bpy.ops.wm.save_as_mainfile(filepath=baked_blend)
    log("WROTE", baked_blend)

    out = out_path(LAYOUT["outputs"]["baked_glb"])
    os.makedirs(os.path.dirname(out), exist_ok=True)
    meshes = [o for o in bpy.data.objects if o.type == 'MESH']
    bpy.ops.object.select_all(action='DESELECT')
    for obj in meshes:
        obj.select_set(True)
    if meshes:
        bpy.context.view_layer.objects.active = meshes[0]
    bpy.ops.export_scene.gltf(
        filepath=out,
        export_format='GLB',
        use_selection=True,
        export_apply=True,
        export_yup=True,
        export_materials='EXPORT',
        export_image_format='AUTO',     # keep our JPEG colour/data maps and PNG normals
        export_cameras=False,
        export_lights=False,
        export_extras=False,
        export_animations=False,
    )
    report["baked_glb"] = out
    report["size_bytes"] = os.path.getsize(out) if os.path.isfile(out) else 0
    report["texture_dir"] = texture_dir
    report["textures"] = TEXTURE_LOG
    log("BAKE_MANIFEST " + json.dumps(report, indent=2))
    log("OK")

main()
